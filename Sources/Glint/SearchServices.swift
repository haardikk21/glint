import AppKit
import Foundation

enum ApplicationIndex {
    static func load() -> [URL] {
        let roots = ["/Applications", "/System/Applications", NSHomeDirectory() + "/Applications"]
        var found: [String: URL] = [:]
        for root in roots {
            guard let walker = FileManager.default.enumerator(
                at: URL(fileURLWithPath: root), includingPropertiesForKeys: [.isDirectoryKey],
                options: [.skipsHiddenFiles, .skipsPackageDescendants]
            ) else { continue }
            for case let url as URL in walker where url.pathExtension.lowercased() == "app" {
                found[url.path] = url
                walker.skipDescendants()
            }
        }
        if let finder = NSWorkspace.shared.urlForApplication(withBundleIdentifier: "com.apple.finder") {
            found[finder.path] = finder
        }
        return found.values.sorted { $0.deletingPathExtension().lastPathComponent.localizedStandardCompare(
            $1.deletingPathExtension().lastPathComponent) == .orderedAscending }
    }
}

enum FileIndex {
    private static let ignored = Set(["node_modules", "target", ".git", ".build", "dist", "build",
                                      ".next", ".venv", "venv", "__pycache__", "vendor", "Pods"])

    static func search(_ query: String) -> [URL] {
        guard query.count >= 2 else { return [] }
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/mdfind")
        process.arguments = ["-onlyin", NSHomeDirectory(), "-name", query]
        let pipe = Pipe()
        process.standardOutput = pipe
        process.standardError = FileHandle.nullDevice
        do { try process.run() } catch { return [] }
        var data = Data()
        var lines = 0
        while data.count < 1_000_000 && lines < 1_000 {
            let chunk = pipe.fileHandleForReading.readData(ofLength: 4096)
            if chunk.isEmpty { break }
            lines += chunk.reduce(0) { $0 + ($1 == 10 ? 1 : 0) }
            data.append(chunk)
        }
        if process.isRunning { process.terminate() }
        process.waitUntilExit()
        let output = String(decoding: data, as: UTF8.self)
        return output.split(separator: "\n").compactMap { path -> URL? in
            let url = URL(fileURLWithPath: String(path))
            guard !url.pathComponents.contains(where: { ignored.contains($0) || $0.hasPrefix(".") }),
                  url.pathExtension.lowercased() != "app" else { return nil }
            return url
        }.prefix(30).map { $0 }
    }
}

@MainActor final class ClipboardMonitor: ObservableObject {
    @Published private(set) var entries: [ClipboardEntry] = []
    private var count = NSPasteboard.general.changeCount
    private var timer: Timer?

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.8, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
    }

    func clear() { entries.removeAll() }

    private func poll() {
        let board = NSPasteboard.general
        guard board.changeCount != count else { return }
        count = board.changeCount
        let types = board.types?.map(\.rawValue) ?? []
        guard !types.contains(where: { $0.contains("ConcealedType") || $0.contains("TransientType") || $0.contains("AutoGeneratedType") }),
              let text = board.string(forType: .string), !text.isEmpty, text.utf8.count <= 100_000,
              entries.first?.text != text else { return }
        entries.insert(ClipboardEntry(text: text), at: 0)
        if entries.count > 50 { entries.removeLast() }
    }
}
